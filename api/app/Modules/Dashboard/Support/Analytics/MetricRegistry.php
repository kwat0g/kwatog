<?php

declare(strict_types=1);

namespace App\Modules\Dashboard\Support\Analytics;

use App\Modules\Auth\Models\User;
use App\Modules\Dashboard\Services\Analytics\Domains\ReturnsPipelineAnalytics;
use App\Modules\Dashboard\Services\Analytics\Domains\WorkOrderLeadTimeAnalytics;

/**
 * The metric dictionary. ONE list, in code.
 *
 * Every entry names the module that owns the number, the single permission that
 * gates it, the domain class that answers it and the columns/indexes it reads.
 * The API (`GET /dashboard/metrics`) and `docs/dashboards/METRICS.md` are both
 * rendered from this list, so a new metric cannot exist only in one of them.
 *
 * Deliberately NOT a role map: candidacy is the permission, exactly like the
 * `dashboard_widgets` registry and the dashboard catalog. A role gains a metric
 * by holding its gate, never by being named here.
 */
final class MetricRegistry
{
    /** @var array<string, MetricDefinition>|null */
    private ?array $definitions = null;

    /** @return array<string, MetricDefinition> keyed by code */
    public function all(): array
    {
        return $this->definitions ??= $this->build();
    }

    public function get(string $code): ?MetricDefinition
    {
        return $this->all()[$code] ?? null;
    }

    public function has(string $code): bool
    {
        return isset($this->all()[$code]);
    }

    /**
     * Every metric whose gate the caller holds. Refused metrics are omitted —
     * the same rule as `PanelGate` and the widget strip — so an unauthorized
     * caller cannot even learn the metric's existence from the catalog.
     *
     * @return array<string, MetricDefinition>
     */
    public function visibleTo(User $user): array
    {
        return array_filter(
            $this->all(),
            static fn (MetricDefinition $definition): bool => $user->hasPermission($definition->permission),
        );
    }

    /** Content hash of the whole dictionary (printed in the generated doc). */
    public function fingerprint(): string
    {
        $parts = array_map(
            static fn (MetricDefinition $definition): string => $definition->code.':'.$definition->fingerprint(),
            $this->all(),
        );

        return substr(hash('sha256', implode('|', $parts)), 0, 16);
    }

    /**
     * Render the dictionary as the Markdown doc. `metrics:doc` prints this, so
     * the checked-in file is generated, never hand-edited.
     */
    public function renderMarkdown(): string
    {
        $lines = [];
        $lines[] = '# OGAMI ERP — Metric Dictionary';
        $lines[] = '';
        $lines[] = '<!-- generated by `php artisan metrics:doc` — do not edit by hand -->';
        $lines[] = '';
        $lines[] = 'Single source: `api/app/Modules/Dashboard/Support/Analytics/MetricRegistry.php`.';
        $lines[] = 'Registry fingerprint: `'.$this->fingerprint().'`.';
        $lines[] = '';
        $lines[] = 'Every metric names the module that owns the number, the one permission that gates it, the';
        $lines[] = 'domain class that answers it, the columns it reads and the indexes it relies on.';
        $lines[] = '`AnalyticsLayerTest` asserts the declared sources/indexes exist in the migrated schema, so a';
        $lines[] = 'renamed column or a skipped index migration fails the suite rather than a dashboard.';
        $lines[] = '';
        $lines[] = 'Regenerate with `php artisan metrics:doc --output=../docs/dashboards/METRICS.md` from the';
        $lines[] = '`api/` directory (or `--check` to fail on drift where `docs/` is reachable).';
        $lines[] = '';
        $lines[] = '## Index';
        $lines[] = '';
        $lines[] = '| Metric | Module | Unit | Direction | Render | Gate | Refresh | TTL |';
        $lines[] = '|---|---|---|---|---|---|---|---|';

        foreach ($this->all() as $definition) {
            $lines[] = sprintf(
                '| `%s` — %s | %s | %s | %s | %s | `%s` | %s | %s |',
                $definition->code,
                $definition->label,
                $definition->module,
                $definition->unit,
                $definition->direction,
                $definition->renderKind,
                $definition->permission,
                $definition->refresh,
                $definition->cacheTtlSeconds === null ? 'setting' : $definition->cacheTtlSeconds.'s',
            );
        }

        $lines[] = '';
        $lines[] = '## Definitions';
        $lines[] = '';

        foreach ($this->all() as $definition) {
            $lines[] = '### `'.$definition->code.'` — '.$definition->label;
            $lines[] = '';
            $lines[] = '- **Module / unit / direction:** '.$definition->module.' · '.$definition->unit.' · '.$definition->direction;
            $lines[] = '- **Gate:** `'.$definition->permission.'` (permission-derived; no role-name branch)';
            $lines[] = '- **Answered by:** `'.$definition->queryClass.'`';
            $lines[] = '- **Aggregation:** '.$definition->aggregation;
            $lines[] = '- **Sources:** '.implode(', ', array_map(static fn (string $source): string => '`'.$source.'`', $definition->sources));
            $lines[] = '- **Indexes relied on:** '.implode(', ', array_map(static fn (string $index): string => '`'.$index.'`', $definition->indexes));
            $lines[] = '- **Refresh / cache:** '.$definition->refresh.' · '.($definition->cacheTtlSeconds === null
                ? 'TTL from `dashboard.analytics.cache_ttl_seconds`'
                : 'TTL '.$definition->cacheTtlSeconds.'s');
            if ($definition->caveats !== []) {
                $lines[] = '- **Known caveats:**';
                foreach ($definition->caveats as $caveat) {
                    $lines[] = '  - '.$caveat;
                }
            }
            $lines[] = '';
        }

        $lines[] = '## Conventions';
        $lines[] = '';
        $lines[] = '- Aggregation happens in SQL (`date_trunc`, `COUNT(*) FILTER`, `AVG`) — never by loading rows';
        $lines[] = '  into PHP and looping.';
        $lines[] = '- Every payload is cached per `scope + filters` with the metric TTL; `flush($code)` bumps a';
        $lines[] = '  version counter (works on array and Redis stores alike), which is the explicit-invalidation seam.';
        $lines[] = '- Row scope is the owning module\'s policy/scope code, never re-expressed here.';
        $lines[] = '- Snapshot-grained metrics (the `kpi.*` family) stay monthly and are read from `kpi_snapshots`;';
        $lines[] = '  anything sub-month aggregates the source tables.';
        $lines[] = '';

        return implode("\n", $lines);
    }

    /** @return array<string, MetricDefinition> */
    private function build(): array
    {
        $definitions = [
            new MetricDefinition(
                code: 'returns.pipeline',
                label: 'Returns pipeline',
                module: 'returns',
                unit: 'count',
                direction: 'lower_better',
                renderKind: 'breakdown',
                permission: 'return_management.view',
                queryClass: ReturnsPipelineAnalytics::class,
                aggregation: 'COUNT(*) grouped by `return_requests.status` and by `type` over the selected '
                    .'window, plus a FILTER count for `pending_approval` and MIN(return_date) for the oldest '
                    .'open return. All counts computed by the database.',
                sources: [
                    'return_requests.status',
                    'return_requests.type',
                    'return_requests.return_date',
                ],
                indexes: ['return_requests_status_index', 'return_requests_type_index', 'return_requests_return_date_index'],
                refresh: 'live',
                caveats: [
                    'Counts returns, not return lines — line-level quantities live on return_request_items.',
                    'Returns whose `return_date` is null are outside every window (they exist but have no date to filter on).',
                    'Statuses are the current state; there is no status history, so a dwell-time reading needs audit_logs.',
                ],
            ),
            new MetricDefinition(
                code: 'production.wo_lead_time',
                label: 'Work-order lead time',
                module: 'production',
                unit: 'hours',
                direction: 'lower_better',
                renderKind: 'trend',
                permission: 'production.dashboard.view',
                queryClass: WorkOrderLeadTimeAnalytics::class,
                aggregation: 'AVG(actual_end - actual_start) in hours per calendar month via date_trunc, over '
                    .'work orders that have both timestamps inside the window; COUNT(*) of those orders alongside.',
                sources: [
                    'work_orders.actual_start',
                    'work_orders.actual_end',
                    'work_orders.machine_id',
                ],
                indexes: ['work_orders_actual_start_index', 'work_orders_actual_end_index', 'work_orders_machine_id_index'],
                refresh: 'live',
                caveats: [
                    'Only completed work orders (both timestamps set) are counted — open WOs are excluded, not zeroed.',
                    'No target lead time exists in settings, so the tile shows the average with no target band.',
                    'Elapsed wall-clock hours include nights and weekends; it is not machine-hours.',
                ],
            ),
        ];

        $keyed = [];

        foreach ($definitions as $definition) {
            if (isset($keyed[$definition->code])) {
                throw new \LogicException("Duplicate metric code [{$definition->code}] in MetricRegistry.");
            }

            $keyed[$definition->code] = $definition;
        }

        ksort($keyed);

        return $keyed;
    }
}
