    Phase 2 (PDF foundation) footer. The `script type="text/php"` block is read by
    DomPDF on render and writes "Page N of M" on every page. The plain
    div above it shows the disclaimer + generator metadata. `$docId` is an
    optional verification string (document number + short checksum); confidential
    documents add a notice line.
--}}
<div class="footer-meta" style="position:fixed; bottom:24px; left:0; right:0;
     text-align:center; font-size:7.5pt; color:#6b6259;
     padding:0 32px;">
  @if (!empty($company['disclaimer']))
    <div style="margin-bottom:2px;">{{ $company['disclaimer'] }}</div>
  @endif
  <div>
    Generated by {{ $generated['by'] ?? 'system' }}
    on {{ $generated['at_text'] ?? now()->format('M d, Y g:i A') }}
    &middot; {{ $company['name'] ?? '' }}
    @if (!empty($docId)) &middot; {{ $docId }} @endif
  </div>
  @if (!empty($confidential))
    <div style="font-weight:bold; letter-spacing:0.5px;">CONFIDENTIAL — do not distribute</div>
  @endif
</div>

<script type="text/php">
  if (isset($pdf)) {
    $font = $fontMetrics->getFont('DejaVu Sans');
    $size = 7;
    // Bottom-right page number; layout is fixed at 8pt, A4 portrait default.
    $pdf->page_text(495, 815, "Page {PAGE_NUM} of {PAGE_COUNT}", $font, $size, [0.42, 0.38, 0.35]);
  }
</script>
