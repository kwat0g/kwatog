const { chromium, expect } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const base = 'http://localhost:18080';
  const browser = await chromium.launch({ headless: true });
  const output = '../.impeccable/review/item-bom-forms';
  fs.mkdirSync(output, { recursive: true });
  const errors = [];
  async function session(email) {
    const context = await browser.newContext({ baseURL: base, viewport: { width: 1440, height: 1000 } });
    await context.request.get('/sanctum/csrf-cookie', { headers: { Origin: base, Referer: base + '/' } });
    async function api(method, route, data) {
      const cookie = (await context.cookies()).find(row => row.name === 'XSRF-TOKEN');
      return context.request.fetch('/api/v1' + route, { method, data, headers: { Origin: base, Referer: base + '/', 'X-XSRF-TOKEN': decodeURIComponent(cookie.value) } });
    }
    const response = await api('POST', '/auth/sign-in', { email, password: 'password' });
    assert(response.ok(), await response.text());
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.url().includes('/api/') && response.status() >= 500) errors.push(`${response.status()} ${response.url()}`); });
    return { page, api };
  }
  async function success(actor, method, route, data) {
    const response = await actor.api(method, route, data);
    assert(response.ok(), await response.text());
    return (await response.json()).data;
  }
  async function fits(page) {
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No document-level horizontal overflow');
  }
  try {
    const admin = await session('admin@ogami.test');
    const warehouse = await session('warehouse@ogami.test');
    const planner = await session('ppc@ogami.test');
    const tag = String(Date.now()).slice(-8);
    const categories = await success(admin, 'GET', '/inventory/item-categories');
    const category = categories.find(row => row.item_type === 'raw_material');
    const finishedCategory = categories.find(row => row.item_type === 'finished_good');
    assert(category && finishedCategory, 'Configured raw-material and finished-good categories');
    const product = await success(admin, 'POST', '/crm/products', { part_number: 'FORM-FG-' + tag, name: 'Form verification ' + tag, unit_of_measure: 'PCS', standard_cost: '20.00', portal_visibility: 'restricted', is_active: true });
    const data = { category_id: category.id, unit_of_measure: 'PCS', standard_cost: '3.0000', reorder_method: 'fixed_quantity', reorder_point: '0', safety_stock: '0', minimum_order_quantity: '1', lead_time_days: 0, is_active: true };
    await success(admin, 'POST', '/inventory/items', { ...data, category_id: finishedCategory.id, code: product.part_number, name: product.name });
    const insert = await success(admin, 'POST', '/inventory/items', { ...data, code: 'FORM-INSERT-' + tag, name: 'Form insert ' + tag, item_type: 'raw_material' });
    const page = warehouse.page;
    await page.goto('/inventory/items/create');
    await expect(page.getByRole('button', { name: 'Create item' })).toBeEnabled();
    await expect(page.getByRole('combobox', { name: /^Item type/ })).toHaveCount(0);
    await page.getByLabel(/^Code/).fill('form-resin-' + tag);
    await page.getByLabel(/^Name/).fill('Form resin ' + tag);
    await page.getByRole('combobox', { name: /^Category/ }).fill(category.name);
    await page.getByRole('option').filter({ hasText: category.name }).last().click();
    await expect(page.getByText('Raw Material · determined by category')).toBeVisible();
    await page.getByRole('combobox', { name: /^Base unit/ }).selectOption('KG');
    await page.getByLabel(/^Standard cost/).fill('4.1234');
    await page.getByRole('combobox', { name: /^Reorder method/ }).selectOption('fixed_quantity');
    await page.getByLabel(/^Minimum order quantity/).fill('0');
    await page.getByRole('button', { name: 'Create item' }).click();
    await expect(page.getByRole('alert').filter({ hasText: 'Minimum order quantity must be greater than zero.' })).toBeVisible();
    await page.getByLabel(/^Minimum order quantity/).fill('25');
    await expect(page.getByRole('alert').filter({ hasText: 'Minimum order quantity must be greater than zero.' })).toHaveCount(0, { timeout: 10000 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await fits(page);
    await page.screenshot({ path: output + '/item-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await fits(page);
    await page.screenshot({ path: output + '/item-mobile.png', fullPage: true });
    const created = page.waitForResponse(response => response.url().endsWith('/api/v1/inventory/items') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Create item' }).click();
    const response = await created;
    assert.equal(response.status(), 201, await response.text());
    const material = (await response.json()).data;
    assert.equal(material.code, 'FORM-RESIN-' + tag);
    assert.equal(material.standard_cost, '4.1234');
    await page.waitForURL('/inventory/items/' + material.id);
    await page.goto('/inventory/items/' + material.id + '/edit');
    await expect(page.getByRole('combobox', { name: /^Base unit/ })).toHaveValue('KG');
    assert((await page.getByRole('combobox', { name: /^Category/ }).inputValue()).includes(category.name));
    await expect(page.getByLabel(/^Minimum order quantity/)).toHaveValue('25.000');
    await expect(page.getByText('Opening stock', { exact: true })).toHaveCount(0);
    const bomPage = planner.page;
    await bomPage.goto('/mrp/boms/create');
    const productSelect = bomPage.getByRole('combobox', { name: /^Finished product/ });
    await productSelect.fill(tag);
    await bomPage.getByRole('option', { name: product.part_number + ' — ' + product.name, exact: true }).click();
    const first = bomPage.getByRole('combobox', { name: 'Component for line 1', exact: true });
    await first.fill(material.code);
    await bomPage.getByRole('option', { name: material.code + ' — ' + material.name, exact: true }).click();
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).not.toBeEditable();
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).toHaveValue('KG');
    await first.fill(insert.code);
    await bomPage.getByRole('option', { name: insert.code + ' — ' + insert.name, exact: true }).click();
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).toHaveValue('PCS');
    await first.fill(material.code);
    await bomPage.getByRole('option', { name: material.code + ' — ' + material.name, exact: true }).click();
    await bomPage.getByLabel('Quantity per unit for line 1').fill('2');
    await bomPage.getByLabel('Waste percentage for line 1').fill('10');
    await bomPage.getByRole('button', { name: 'Add component' }).click();
    const second = bomPage.getByRole('combobox', { name: 'Component for line 2' });
    await second.fill(material.code);
    await expect(bomPage.getByRole('option', { name: material.code + ' — ' + material.name, exact: true })).toBeDisabled();
    await second.fill(insert.code);
    await bomPage.getByRole('option', { name: insert.code + ' — ' + insert.name, exact: true }).click();
    await bomPage.getByLabel('Quantity per unit for line 2').fill('1');
    const published = bomPage.waitForResponse(response => response.url().endsWith('/api/v1/mrp/boms') && response.request().method() === 'POST');
    await bomPage.getByRole('button', { name: 'Save BOM' }).click();
    const bomResponse = await published;
    assert.equal(bomResponse.status(), 201, await bomResponse.text());
    const bom = (await bomResponse.json()).data;
    assert.equal(bom.version, 1);
    await bomPage.waitForURL('/mrp/boms/' + bom.id);
    await bomPage.goto('/mrp/boms/' + bom.id + '/edit');
    await expect(bomPage.getByLabel('Quantity per unit for line 1')).toHaveValue('2.0000');
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).toHaveValue('KG');
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).not.toBeEditable();
    await bomPage.getByLabel('Quantity per unit for line 1').fill('3');
    const updated = bomPage.waitForResponse(response => response.url().endsWith('/api/v1/mrp/boms/' + bom.id) && response.request().method() === 'PUT');
    await bomPage.getByRole('button', { name: 'Save new version' }).click();
    const updatedResponse = await updated;
    assert(updatedResponse.ok(), await updatedResponse.text());
    const version2 = (await updatedResponse.json()).data;
    assert.equal(version2.version, 2);
    const old = await success(planner, 'GET', '/mrp/boms/' + bom.id);
    assert.equal(old.is_active, false);
    assert.equal(old.items[0].quantity_per_unit, '2.0000');
    await bomPage.waitForURL('/mrp/boms/' + version2.id);
    await bomPage.goto('/mrp/boms/create');
    await productSelect.fill(tag);
    await bomPage.getByRole('option', { name: product.part_number + ' — ' + product.name, exact: true }).click();
    await expect(bomPage.getByText(/Saving replaces active version 2/)).toBeVisible();
    await first.fill(material.code);
    await bomPage.getByRole('option', { name: material.code + ' — ' + material.name, exact: true }).click();
    await bomPage.getByLabel('Quantity per unit for line 1').fill('2');
    await bomPage.getByLabel('Waste percentage for line 1').fill('10');
    for (let count = 0; count < 19; count++) await bomPage.getByRole('button', { name: 'Add component' }).click();
    const region = bomPage.getByRole('region', { name: 'BOM component table' });
    const dimensions = await region.evaluate(element => ({ height: element.clientHeight, scroll: element.scrollHeight }));
    assert(dimensions.height <= 520 && dimensions.scroll > dimensions.height, JSON.stringify(dimensions));
    await region.evaluate(element => { element.scrollTop = 0; });
    await bomPage.evaluate(() => { document.activeElement.blur(); window.scrollTo(0, 0); });
    await fits(bomPage);
    await bomPage.screenshot({ path: output + '/bom-desktop.png', fullPage: true });
    await bomPage.setViewportSize({ width: 390, height: 844 });
    await fits(bomPage);
    await bomPage.screenshot({ path: output + '/bom-mobile.png', fullPage: true });
    await first.click();
    await first.fill(insert.code);
    await expect(bomPage.getByRole('option', { name: insert.code + ' — ' + insert.name, exact: true })).toBeVisible();
    await fits(bomPage);
    await bomPage.screenshot({ path: output + '/bom-search-mobile.png' });
    await first.press('ArrowDown');
    await first.press('Enter');
    await expect(bomPage.getByRole('textbox', { name: 'Unit for line 1', exact: true })).toHaveValue('PCS');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ roles: ['warehouse', 'ppc', 'admin'], item: material.id, bom: version2.id, item_create: true, edit_prefill: true, duplicate_prevention: true, automatic_units: true, locked_units: true, combined_search: true, keyboard_selection: true, archived_history: true, active_version_warning: true, twenty_lines_bounded: true, desktop_mobile_overflow: false, browser_errors: errors }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
