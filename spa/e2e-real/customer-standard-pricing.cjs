const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const base = 'http://localhost:18080';
  const browser = await chromium.launch({ headless: true });
  const output = path.resolve(__dirname, '../../.impeccable/review/customer-pricing');
  fs.mkdirSync(output, { recursive: true });
  const errors = [];
  const orders = [];
  const products = [];
  const agreements = [];
  async function session(email) {
    const context = await browser.newContext({ baseURL: base, viewport: { width: 1440, height: 1000 } });
    await context.request.get('/sanctum/csrf-cookie', { headers: { Origin: base, Referer: base + '/' } });
    const token = () => context.cookies().then(cookies => decodeURIComponent(cookies.find(cookie => cookie.name === 'XSRF-TOKEN').value));
    async function api(method, route, data, headers = {}) {
      return context.request.fetch('/api/v1' + route, { method, data, headers: { Origin: base, Referer: base + '/', 'X-XSRF-TOKEN': await token(), ...headers } });
    }
    const login = await api('POST', '/auth/sign-in', { email, password: 'password' });
    assert(login.ok(), await login.text());
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    return { context, page, api };
  }
  const admin = await session('admin@ogami.test');
  const officer = await session('customerservice@ogami.test');
  const customer = await session('portal@cust.test');
  const sales = await session('crm@ogami.test');
  try {
    console.log('Role sessions established.');
    const account = (await (await customer.api('GET', '/b2b/customer/me')).json()).data;
    const customerList = (await (await officer.api('GET', '/crm/customers')).json()).data;
    const buyer = customerList.find(row => row.id === account.customer?.id || row.id === account.customer_id) || customerList.find(row => row.name.includes('Toyota'));
    assert(buyer, 'Customer lookup must find the customer account.');
    const suffix = String(Date.now()).slice(-8);
    const fixture = { part_number: 'PRICE-' + suffix, name: 'Pricing E2E standard product ' + suffix, unit_of_measure: 'PCS', standard_cost: '20.00', base_selling_price: '30.00', minimum_selling_price: '25.00', portal_visibility: 'standard', is_active: true };
    const created = await admin.api('POST', '/crm/products', fixture);
    assert.equal(created.status(), 201, await created.text());
    const product = (await created.json()).data;
    products.push(product.id);
    const privateResponse = await admin.api('POST', '/crm/products', { ...fixture, part_number: 'PRIVATE-' + suffix, name: 'Pricing E2E private product ' + suffix, portal_visibility: 'restricted', portal_customer_ids: [buyer.id] });
    assert.equal(privateResponse.status(), 201, await privateResponse.text());
    const privateProduct = (await privateResponse.json()).data;
    products.push(privateProduct.id);
    const hiddenResponse = await admin.api('POST', '/crm/products', { ...fixture, part_number: 'HIDDEN-' + suffix, name: 'Pricing E2E hidden product ' + suffix, portal_visibility: 'restricted' });
    assert.equal(hiddenResponse.status(), 201, await hiddenResponse.text());
    const hidden = (await hiddenResponse.json()).data;
    products.push(hidden.id);
    console.log('Pricing products created.');
    const catalog = (await (await customer.api('GET', '/b2b/customer/catalog')).json()).data;
    assert(catalog.some(row => row.id === product.id && row.price_source === 'base'));
    assert(catalog.some(row => row.id === privateProduct.id));
    assert(!catalog.some(row => row.id === hidden.id));
    assert(!JSON.stringify(catalog).includes('minimum_selling_price'));
    const date = new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10);
    const to = new Date(Date.now() + 30 * 86400000).toISOString().slice(0, 10);
    await customer.page.goto('/portal/customer/orders/new');
    await customer.page.getByLabel('Requested delivery date', { exact: true }).fill(date);
    await customer.page.getByRole('button', { name: 'Add products', exact: true }).click();
    await customer.page.getByRole('textbox', { name: 'Search products' }).fill(fixture.part_number);
    await customer.page.getByRole('button', { name: `Add ${fixture.name} to order`, exact: true }).click();
    await customer.page.getByRole('button', { name: 'Done selecting products' }).click();
    await customer.page.getByRole('spinbutton', { name: 'Quantity for ' + fixture.part_number, exact: true }).fill('100');
    await customer.page.waitForFunction(() => document.querySelector('[data-testid="order-total"]')?.textContent.includes('3,360.00'));
    const placeRequest = customer.page.waitForResponse(response => response.url().endsWith('/b2b/customer/orders') && response.request().method() === 'POST');
    await customer.page.getByRole('button', { name: 'Submit order for review', exact: true }).click();
    const placed = await placeRequest;
    assert.equal(placed.status(), 201, await placed.text());
    const order = (await placed.json()).data;
    orders.push(order.id);
    assert.equal(order.items[0].price_source, 'base');
    assert.equal(order.total_amount, '3360.00');
    console.log('Base order placed.');
    await admin.page.goto('/crm/products/' + product.id + '/edit');
    await admin.page.getByLabel('Base selling price', { exact: true }).waitFor();
    assert.equal(await admin.page.getByLabel('Base selling price', { exact: true }).inputValue(), '30.00');
    await admin.page.screenshot({ path: output + '/product-pricing-desktop.png', fullPage: true });

    console.log('Product form verified.');
    await officer.page.goto('/crm/price-agreements/create');
    const productSelect = officer.page.getByRole('combobox', { name: /^Product/ });
    await productSelect.waitFor();
    await productSelect.fill(fixture.part_number);
    await officer.page.waitForFunction(id => Array.from(document.querySelector('select[name="product_id"]')?.options ?? []).some(option => option.value === id), product.id);
    await officer.page.getByRole('option', { name: fixture.part_number + ' · ' + fixture.name, exact: true }).click();
    console.log('Agreement product selected.');
    await officer.page.getByRole('combobox', { name: /^Customer/ }).fill(buyer.name);
    await officer.page.getByRole('option', { name: (buyer.code ? buyer.code + ' · ' : '') + buyer.name, exact: true }).click();
    console.log('Agreement customer selected.');
    await officer.page.getByRole('combobox', { name: /^Pricing method/ }).selectOption('tiered');
    await officer.page.getByLabel(/^Fallback price/).fill('28.00');
    await officer.page.getByLabel(/^Effective from/).fill(date);
    await officer.page.getByLabel(/^Effective to/).fill(to);
    await officer.page.getByRole('button', { name: 'Add tier', exact: true }).click();
    await officer.page.getByLabel('Minimum quantity for tier 1', { exact: true }).fill('100');
    await officer.page.getByLabel('Unit price for tier 1', { exact: true }).fill('24.00');
    await officer.page.getByRole('button', { name: 'Create agreement', exact: true }).click();
    await officer.page.getByText(/Price must be at least .*25\.00\./).waitFor({timeout:10000});
    await officer.page.getByLabel('Unit price for tier 1', { exact: true }).fill('26.00');
    await officer.page.getByRole('heading', { name: 'Agreement summary' }).waitFor();
    await officer.page.screenshot({ path: output + '/agreement-desktop.png', fullPage: true });
    await officer.page.setViewportSize({ width: 390, height: 844 });
    await officer.page.screenshot({ path: output + '/agreement-mobile.png', fullPage: true });
    assert(await officer.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    const agreementRequest = officer.page.waitForResponse(response => response.url().endsWith('/crm/price-agreements') && response.request().method() === 'POST');
    await officer.page.getByRole('button', { name: 'Create agreement', exact: true }).click();
    const agreementResponse = await agreementRequest;
    assert.equal(agreementResponse.status(), 201, await agreementResponse.text());
    const agreement = (await agreementResponse.json()).data;
    agreements.push(agreement.id);
    assert.equal((await sales.api('POST', '/crm/price-agreements', { product_id: product.id, customer_id: buyer.id, price: '28.00', effective_from: date, effective_to: to })).status(), 403);
    assert.equal((await officer.api('PUT', '/crm/price-agreements/' + agreement.id, { price: '24.00' })).status(), 422);

    console.log('Agreement and role guards verified.');
    await customer.page.goto('/portal/customer/orders/' + order.id + '/edit');
    await customer.page.getByRole('textbox', { name: 'Order note (optional)' }).fill('Notes only after new pricing.');
    const updateRequest = customer.page.waitForResponse(response => response.url().endsWith('/b2b/customer/orders/' + order.id) && response.request().method() === 'PUT');
    await customer.page.getByRole('button', { name: 'Save changes', exact: true }).click();
    const updatedResponse = await updateRequest;
    assert(updatedResponse.ok(), await updatedResponse.text());
    const updated = (await updatedResponse.json()).data;
    assert.equal(updated.total_amount, '3360.00');
    assert.equal(updated.items[0].id, order.items[0].id);
    const item = { product_id: product.id, quantity: '100', delivery_date: date };
    const quoted = await customer.api('POST', '/b2b/customer/orders/quote', { items: [item] });
    assert(quoted.ok(), await quoted.text());
    const quote = (await quoted.json()).data;
    assert.equal(quote.total_amount, '2912.00');
    assert.equal(quote.items[0].price_source, 'agreement');
    assert((await officer.api('PUT', '/crm/price-agreements/' + agreement.id, { tiers: [{ min_qty: 100, unit_price: '27.00' }] })).ok());
    const stale = await customer.api('POST', '/b2b/customer/orders', { items: [item], quote_signature: quote.signature }, { 'Idempotency-Key': 'stale-' + suffix });
    assert.equal(stale.status(), 422, await stale.text());
    assert((await stale.json()).errors.quote_signature);
    assert((await officer.api('PUT', '/crm/price-agreements/' + agreement.id, { tiers: [{ min_qty: 100, unit_price: '26.00' }] })).ok());

    await customer.page.goto('/portal/customer/orders/new');
    await customer.page.getByLabel('Requested delivery date', { exact: true }).fill(date);
    await customer.page.getByRole('button', { name: 'Add products', exact: true }).click();
    await customer.page.getByRole('textbox', { name: 'Search products' }).fill(fixture.part_number);
    await customer.page.getByRole('button', { name: `Add ${fixture.name} to order`, exact: true }).click();
    await customer.page.getByRole('button', { name: 'Done selecting products' }).click();
    await customer.page.getByRole('spinbutton', { name: 'Quantity for ' + fixture.part_number, exact: true }).fill('100');
    await customer.page.waitForFunction(() => document.querySelector('[data-testid="order-total"]')?.textContent.includes('2,912.00'));
    await customer.page.getByText('Agreed price', { exact: true }).waitFor();
    await customer.page.screenshot({ path: output + '/customer-volume-desktop.png', fullPage: true });
    await customer.page.setViewportSize({ width: 390, height: 844 });
    await customer.page.screenshot({ path: output + '/customer-volume-mobile.png', fullPage: true });
    assert(await customer.page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    const secondRequest = customer.page.waitForResponse(response => response.url().endsWith('/b2b/customer/orders') && response.request().method() === 'POST');
    await customer.page.getByRole('button', { name: 'Submit order for review', exact: true }).click();
    const secondResponse = await secondRequest;
    assert.equal(secondResponse.status(), 201, await secondResponse.text());
    const second = (await secondResponse.json()).data;
    orders.push(second.id);
    assert.equal(second.total_amount, quote.total_amount);
    assert.equal(second.items[0].price_source, 'agreement');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ environment: 'isolated audit', roles: ['administrator', 'customer service officer', 'sales officer', 'customer'], standardWithoutAgreement: 'passed', privateAccess: 'passed', agreedVolumeVat: 'passed', staleQuoteRejected: 'passed', notesOnlyPricesPreserved: 'passed', floorValidation: 'passed', salesManageDenied: 'passed', mobileOverflow: 'passed', browserErrors: errors }));
  } catch (error) {
    console.log('OFFICER PAGE', (await officer.page.locator('body').innerText()).slice(-6000));
    console.log('CUSTOMER PAGE', (await customer.page.locator('body').innerText()).slice(-2000));
    throw error;
  } finally {
    for (const id of orders) await customer.api('POST', '/b2b/customer/orders/' + id + '/cancel', { reason: 'Pricing E2E completed.' });
    for (const id of agreements) await officer.api('DELETE', '/crm/price-agreements/' + id);
    for (const id of products) await admin.api('DELETE', '/crm/products/' + id);
    await browser.close();
  }
})().catch(error => { console.error(error); process.exit(1); });
